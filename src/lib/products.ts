export function slugifyBrand(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function formatTk(n: number): string {
  return `Tk ${n.toLocaleString("en-IN")}`;
}

export function productHref(product: Product): string {
  return `/product/${product.slug}`;
}

export function galleryFor(product: Product): string[] {
  const others = products.filter((p) => p.id !== product.id).slice(0, 2);
  return [product.image, ...others.map((p) => p.image)];
}

