export function uniqueBrands(list: Product[]): string[] {
  return [...new Set(list.map((p) => p.brand))].sort();
}

export function uniqueOptions(
  list: Product[],
  key: "strap" | "dial" | "gender",
): string[] {
  return [...new Set(list.map((p) => p[key]))].sort();
}

